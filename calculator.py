print("SIMPLE CALCULATOR")
print("ENTER THE TWO NUMBER TO PERFORM CALCULATION")
NUMBER_1=int(input("ENTER THE FIRST VALUE :"))
NUMBER_2=int(input("ENTER THE SECOND VALUE :"))
print("FIRST VALUE =",NUMBER_1)
print("SECOND VALUE =",NUMBER_2)
OPERATOR=(input("ENTER THE OPERATOR :"))
if OPERATOR=="+":
    print("ANSWER :",NUMBER_1+NUMBER_2)
elif OPERATOR=="-":
    print("ANSWER :",NUMBER_1-NUMBER_2)
elif OPERATOR=="*":
    print("ANSWER :",NUMBER_1*NUMBER_2)
elif OPERATOR=="/":
    print("ANSWER :",NUMBER_1/NUMBER_2)
elif OPERATOR=="%":
    print("ANSWER :",NUMBER_1%NUMBER_2)
elif OPERATOR=="all":
    print("ADDITION :",NUMBER_1+NUMBER_2)
    print("SUBTRACTION :",NUMBER_1-NUMBER_2)
    print("MULTIPLICATION :",NUMBER_1*NUMBER_2)
    print("DIVISION :",NUMBER_1/NUMBER_2)
    print("MODULES :",NUMBER_1%NUMBER_2)
else:
    print("INVALID OPERATOR")